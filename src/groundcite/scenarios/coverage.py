"""Render ``docs/scenario-coverage.md`` from the library and the generated sets."""

from __future__ import annotations

import re
from collections import Counter
from collections.abc import Mapping, Sequence
from typing import Any

from groundcite.scenarios.generator import CATEGORIES, QUOTAS, SPLIT_OFFSETS
from groundcite.scenarios.library import Library


def _scheme(snippet_id: str) -> str:
    return re.sub(r"[0-9]+", "#", snippet_id)


def render_coverage(
    lib: Library, sets: Mapping[str, Sequence[Mapping[str, Any]]], master_seed: int
) -> str:
    lines = [
        "# Scenario coverage",
        "",
        "Generated by `scripts/gen_scenarios.py`; do not edit by hand. Regenerate with:",
        "",
        "```sh",
        f"uv run scripts/gen_scenarios.py --seed {master_seed} --out data/scenarios \\",
        "    --coverage-doc docs/scenario-coverage.md",
        "```",
        "",
        "All snippets, vehicles and complaints are synthetic and hand-written. They are not",
        "real service information and are not copied from any manual or bulletin. Vehicles are",
        "described generically (body style, engine, transmission, model year), with no",
        "manufacturer names.",
        "",
        "**Scope:** light-duty passenger vehicles, symptom to first diagnostic check, 2-5 snippets",
        f"per scenario, {len(lib.systems())} vehicle systems (at most 8).",
        "",
        "## Systems",
        "",
        "| System | Training families | Reserved (held-out) families | Library snippets |",
        "| --- | --- | --- | --- |",
    ]
    snippets_by_system = Counter(s.system for s in lib.snippets.values())
    for system in lib.systems():
        train = [f.name for f in lib.pool(reserved=False) if f.system == system]
        held = [f.name for f in lib.pool(reserved=True) if f.system == system]
        lines.append(
            f"| {system} | {', '.join(train) or '-'} | {', '.join(held) or '-'} "
            f"| {snippets_by_system[system]} |"
        )

    lines += [
        "",
        "## Symptom families",
        "",
        "Reserved families appear only in `heldout.jsonl`, and held-out scenarios use only",
        "snippets from reserved families (see `data/reserved_families.txt`).",
        "",
        "| Family | System | Split | Symptom | Chain | Near-miss | Close |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name, fam in sorted(lib.families.items()):
        split = "reserved" if name in lib.reserved else "training"
        lines.append(
            f"| {name} | {fam.system} | {split} | {fam.symptom} | {len(fam.chain)} "
            f"| {len(fam.near_miss)} | {len(fam.close)} |"
        )

    lines += [
        "",
        "## Sets",
        "",
        "Category counts, with the target share from the requirements' scenario mix (each set must",
        "be within 5 points). `ablation` is a quota-balanced subset of `eval_own`.",
        "",
        "| Category | Target | " + " | ".join(sets) + " |",
        "| --- | --- | " + " | ".join("---" for _ in sets) + " |",
    ]
    counts = {name: Counter(row["category"] for row in rows) for name, rows in sets.items()}
    for category in CATEGORIES:
        cells = [
            f"{counts[name][category]} ({100 * counts[name][category] / len(rows):.0f}%)"
            for name, rows in sets.items()
        ]
        lines.append(f"| {category} | {QUOTAS[category]}% | " + " | ".join(cells) + " |")
    lines.append("| total | | " + " | ".join(str(len(rows)) for rows in sets.values()) + " |")

    lines += [
        "",
        "| Measure | " + " | ".join(sets) + " |",
        "| --- | " + " | ".join("---" for _ in sets) + " |",
    ]
    measures: list[tuple[str, list[str]]] = []
    for label, fn in (
        ("cite / abstain gold", _modes),
        ("families", lambda rows: str(len({r["family"] for r in rows}))),
        (
            "ID schemes",
            lambda rows: str(len({_scheme(s["id"]) for r in rows for s in r["snippets"]})),
        ),
        ("snippets per scenario", _snippet_range),
        (
            "tagged pressure",
            lambda rows: str(
                sum("pressure" in r["tags"] or r["category"] == "pressure" for r in rows)
            ),
        ),
        (
            "with a near-miss snippet",
            lambda rows: str(sum(bool(r["gold"]["near_miss_ids"]) for r in rows)),
        ),
        (
            "gold snippets that are bulletins",
            lambda rows: _kind_share(rows, "supporting_ids", "tsb"),
        ),
        (
            "near-misses that are manual-kind",
            lambda rows: _kind_share(rows, "near_miss_ids", "manual"),
        ),
    ):
        measures.append((label, [fn(rows) for rows in sets.values()]))
    for label, cells in measures:
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    schemes = sorted(
        {_scheme(s["id"]) for rows in sets.values() for r in rows for s in r["snippets"]}
    )
    lines += [
        "",
        "## IDs and seeds",
        "",
        "Snippet IDs are re-drawn for every scenario from these visibly synthetic schemes (digit",
        "runs shown as `#`), and snippet order is shuffled per scenario: "
        + ", ".join(f"`{s}`" for s in schemes)
        + ".",
        "",
        "Snippet kind is not a shortcut to the gold citation. An ID's style (bulletin-like or",
        "manual-like) is drawn independently of the snippet's kind, gold snippets are bulletins",
        "about half the time, near-misses are manual procedures about half the time, and wording",
        "such as a `Repair:` line or an `Applies to all` opener appears on gold and non-gold",
        "snippets alike (checked by `tests/test_kind_balance.py`).",
        "",
        "Every near-miss is a twin of a chain snippet in its family: the same text with only its",
        "applicability scope changed (an engine list, a year range, a transmission, a body or one",
        "operating condition). Gold and near-miss therefore match on length, punctuation, numbers",
        "and opener, and in distractor scenarios the first near-miss is the gold's own twin. No",
        "single surface heuristic and no ridge probe on surface features picks the gold on more",
        "than 60% of distractor scenarios (checked by `tests/test_shortcuts.py` and",
        "`tests/test_twins.py`).",
        "",
        f"Master seed {master_seed}. Scenario seeds are `master * 1000000 + offset + index`, with",
        "disjoint offsets per split: "
        + ", ".join(f"`{split}` {offset}" for split, offset in SPLIT_OFFSETS.items())
        + ".",
        "",
    ]
    return "\n".join(lines)


def _modes(rows: Sequence[Mapping[str, Any]]) -> str:
    modes = Counter(r["gold"]["mode"] for r in rows)
    return f"{modes['cite']} / {modes['abstain']}"


def _kind_share(rows: Sequence[Mapping[str, Any]], gold_key: str, kind: str) -> str:
    """How many of the snippets listed under ``gold[gold_key]`` are of ``kind``."""
    kinds = Counter(
        {s["id"]: s["kind"] for s in r["snippets"]}[snippet_id]
        for r in rows
        for snippet_id in r["gold"][gold_key]
    )
    total = sum(kinds.values())
    share = 100 * kinds[kind] / total if total else 0.0
    return f"{kinds[kind]} / {total} ({share:.0f}%)"


def _snippet_range(rows: Sequence[Mapping[str, Any]]) -> str:
    sizes = [len(r["snippets"]) for r in rows]
    return f"{min(sizes)}-{max(sizes)}"
