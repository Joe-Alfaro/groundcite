    assert len(judge.calls) == N_TURNS
    for i, row in enumerate(rows):
        validate_transcript_row(row)
        assert set(TRANSCRIPT_FIELDS) <= set(row)
        assert row["conversation_id"] == "conv-001"
        assert row["turn_index"] == i
        assert row["run_id"] == "run-1"
        assert row["model"] == "mock:steady"
        assert row["strategy"] == STRATEGY
        assert row["reply"] == transcript.turns[i].reply
        assert row["gold"]["mode"] == script.turns[i].gold["mode"]
        assert row["prompt_sha256"] == prompt_sha256(STRATEGY)
        assert row["rubric_sha256"] == rubric_sha256()
        assert row["generation_error"] is None
    assert len({r["scenario_id"] for r in rows}) == N_TURNS


