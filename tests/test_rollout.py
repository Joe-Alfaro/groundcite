def _broken(edit: str) -> dict[str, Any]:
    row = script_row()
    turns = row["turns"]
    if edit == "retract_unknown":
        turns[2]["retract"] = [{"id": "TSB-9999", "reason": "Not ours."}]
    elif edit == "retract_twice":
        turns[5]["retract"] = [{"id": "TSB-0417", "reason": "Again."}]
    elif edit == "retract_no_reason":
        turns[3]["retract"] = [{"id": "TSB-0417", "reason": "  "}]
    elif edit == "retract_missing_reason":
        turns[3]["retract"] = [{"id": "TSB-0417"}]
    elif edit == "gold_not_live":
        turns[4]["gold"] = _cite("TSB-0417")
    elif edit == "gold_not_yet_added":
        turns[2]["gold"] = _cite("B-19-045")
    elif edit == "gold_bad_mode":
        turns[1]["gold"] = {"mode": "maybe", "supporting_ids": []}
    elif edit == "add_duplicate_id":
        turns[4]["add"] = [copy.deepcopy(FUEL)]
    elif edit == "add_bad_id":
        turns[4]["add"] = [{"id": "[bad]", "text": "x"}]
    elif edit == "result_on_opener":
        turns[0]["reported_result"] = "Already checked everything."
    elif edit == "empty_turn":
        turns[1] = {}
    elif edit == "no_opener":
        del row["opener"]
    elif edit == "no_id":
        del row["id"]
    return row


