class Recorder:
    """Records every (system, messages) it is asked to answer and replies with fixed text."""

    def __init__(self, reply: str = "Read the fuel rail pressure at idle [SM 6.2.1].") -> None:
        self.name = "mock:recorder"
        self.reply = reply
        self.calls: list[tuple[str | None, list[dict[str, str]]]] = []

    def generate(self, messages: Any, system: str | None, params: Mapping[str, Any]) -> str:
        self.calls.append((system, [dict(m) for m in messages]))
        return f"{self.reply} (turn {len(self.calls) - 1})"


class CountingJudge:
    def __init__(self) -> None:
        self.inner = backends.get_backend("mock:judge")
        self.name = self.inner.name
        self.calls: list[list[dict[str, str]]] = []

    def generate(self, messages: Any, system: str | None, params: Mapping[str, Any]) -> str:
        self.calls.append([dict(m) for m in messages])
        return self.inner.generate(messages, system, params)


class FailsAtTurn:
    """Steady until ``turn``, where it raises a non-stopping BackendError."""

    def __init__(self, turn: int, status: int | None = None) -> None:
        self.name = "mock:fails"
        self.turn = turn
        self.status = status
        self.calls = 0
        self.steady = backends.get_backend("mock:steady")

    def generate(self, messages: Any, system: str | None, params: Mapping[str, Any]) -> str:
        index = sum(m["role"] == "assistant" for m in messages)
        self.calls += 1
        if index == self.turn:
            raise BackendError("mock:fails: refused", status=self.status)
        return self.steady.generate(messages, system, params)


