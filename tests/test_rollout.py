def write_scripts(path: Path, rows: list[dict[str, Any]]) -> Path:
    path.write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8")
    return path


def scripts_file(tmp_path: Path, n: int = 3) -> Path:
    return write_scripts(
        tmp_path / "scripts.jsonl", [script_row(f"conv-{i:03d}") for i in range(1, n + 1)]
    )


def load_one(ro: ModuleType, tmp_path: Path, row: dict[str, Any] | None = None) -> Any:
    [script] = ro.load_scripts(write_scripts(tmp_path / "one.jsonl", [row or script_row()]))
