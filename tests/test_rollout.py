"""Red tests for the conversation-rollout harness (hardening option H1, long-conversation drift).

Every assistant turn of a scripted 8-12 turn conversation is generated by the model under test,
then each turn is scored by the deterministic checks and the judge against that turn's live
snippets and gold. The contract under test (see ``_private/decisions.md`` for the rationale):

``groundcite.rollout``
  - ``load_scripts(path) -> list[ConversationScript]``: JSONL rows with ``id``, ``opener``,
    ``snippets_initial`` and ``turns`` (8-12). A turn may carry ``text``, ``add`` (snippets),
    ``retract`` (``[{"id", "reason"}]``), ``reported_result``, ``pressure`` and ``gold``. Turn 0
    is the opener turn. Malformed rows raise ``EvalSetError`` naming the line.
  - ``live_snippets(script, turn_index)``: the snippets live at that turn, after its own ops.
  - ``turn_scenario(script, turn_index, replies) -> Scenario``: the conversation so far (user
    turns plus the earlier ``replies``), ``provided_ids`` = the live IDs, ``gold`` = the turn's.
  - ``rollout(script, subject, strategy, *, params=None) -> Transcript``: ``Transcript`` has
    ``conversation_id``, ``model``, ``strategy`` and ``turns``; each turn has ``turn_index``,
    ``scenario``, ``reply`` and ``generation_error``. Turn i is generated from
    ``render_messages(turn_scenario(script, i, replies[:i]), strategy)``. A generation failure
    ends the conversation; the remaining turns are kept as failures, never dropped.
  - ``score_transcript(transcript, judge, *, run_id, model_revision=None, params=None)``: one
    transcript row per assistant turn: the existing fields plus ``conversation_id`` and
    ``turn_index``.
  - ``meets_rollout_bar(cell)``: per-conversation pass rate and mean Robustness against the
    committed reliability bar.

``groundcite.report.aggregate_scores`` (extended, not forked): when rows carry
``conversation_id``, each cell also has ``n_conversations``, ``conversation_pass_rate``,
``first_failure_turns`` and ``spec_adherence_by_turn``. Single-turn cells are unchanged.

Mocks: ``mock:steady`` holds the contract on every turn (cites a live snippet, abstains when none
is live); ``mock:drift@k`` behaves like ``mock:steady`` for turn indices < k and like
``mock:naive`` from turn index k on.

CLI: ``scripts/run_rollouts.py --model M --strategy S --scripts PATH [--limit N] [--dry-run]
[--resume] [--run-id ID] [--judge J] [--allow-dirty] [--out DIR]``, loaded in-process.

The format doc is ``docs/conversation-format.md``. Sockets are blocked and keys are unset.
"""

