def _load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("run_rollouts", SCRIPT)
    assert spec is not None and spec.loader is not None, f"{SCRIPT} is missing"
    assert SCRIPT.is_file(), f"{SCRIPT} is missing"
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def run_rollouts(argv: list[str]) -> int:
    try:
        return int(_load_script().main(argv))
    except SystemExit as exc:
        return int(exc.code or 0)


def cli_argv(scripts: Path, out: Path, model: str = "mock:steady", *extra: str) -> list[str]:
    return [
        "--model",
        model,
        "--strategy",
        STRATEGY,
        "--scripts",
        str(scripts),
        "--judge",
        "mock",
        "--allow-dirty",
        "--out",
        str(out),
        *extra,
    ]


def _calls(stdout: str, kind: str) -> int:
    match = re.search(rf"(?mi)^\s*{kind} calls:\s*(\d+)\s*$", stdout)
    assert match, f"no '{kind} calls: N' line in:\n{stdout}"
    return int(match.group(1))


