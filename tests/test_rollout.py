def test_conversation_rows_keep_every_existing_metric() -> None:
    conv_rows = _conversation("c1", 6) + _conversation("c2", None) + _conversation("c3", 2)
    plain_rows = [
        {k: v for k, v in r.items() if k not in ("conversation_id", "turn_index")}
        for r in conv_rows
    ]
    [with_conv] = aggregate_scores(conv_rows, seed=0)
    [plain] = aggregate_scores(plain_rows, seed=0)
    assert {k: with_conv[k] for k in plain} == plain


def test_conversation_metrics() -> None:
    rows = (
        _conversation("c1", None)
        + _conversation("c2", None)
        + _conversation("c3", 9)
        + _conversation("c4", 3)
        + _conversation("c5", 9)
    )
    [cell] = aggregate_scores(rows, seed=0)
    assert cell["n"] == 5 * N_TURNS
    assert cell["n_conversations"] == 5
    assert cell["conversation_pass_rate"] == pytest.approx(2 / 5)
    assert cell["first_failure_turns"] == {"3": 1, "9": 2}
    by_turn = cell["spec_adherence_by_turn"]
    assert list(by_turn) == [str(t) for t in range(N_TURNS)]
    assert by_turn["0"] == pytest.approx(1.0)
    assert by_turn["3"] == pytest.approx(4 / 5)
    assert by_turn["9"] == pytest.approx(2 / 5)
    assert cell["robustness_mean"] == pytest.approx(
        sum(r["score"]["robustness"] for r in rows) / len(rows)
    )


